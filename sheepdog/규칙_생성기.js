// 규칙_생성기.js — 양몰이 v5
// 탄 번호 하나로 스테이지 전체 규칙을 만든다. 손으로 만드는 건 손제작탄 표뿐.
// v4 index.html에 <script src="규칙_생성기.js"> 로 끼우고 스테이지_규칙(n) 호출.

const 배경_순서 = ["앞마당", "뒷산", "눈고개", "강가", "화산"];
const 양_색_순서 = ["흰", "검", "갈", "점박이"];

function 반올림(x) { return Math.round(x); }
function 상한(x, m) { return Math.min(x, m); }
function 하한(x, m) { return Math.max(x, m); }

// 1~10탄, 보스탄만 손으로 덮어쓴다. 나머지는 공식.
const 손제작탄 = {
  1:  { 양총수: 3,  무리크기: [1, 1], 우리수: 1, 늑대: false, 튜토리얼: "이동" },
  2:  { 양총수: 4,  무리크기: [2, 2], 우리수: 1, 늑대: false, 튜토리얼: "짖기" },
  3:  { 양총수: 5,  무리크기: [2, 3], 우리수: 1, 늑대: false },
  4:  { 양총수: 6,  무리크기: [2, 3], 우리수: 1, 늑대: false, 방해: ["바위"] },
  5:  { 양총수: 6,  무리크기: [2, 3], 우리수: 1, 늑대: false, 방해: ["개울"] },
  6:  { 양총수: 7,  무리크기: [2, 3], 우리수: 1, 늑대: false, 방해: ["바위", "개울"] },
  7:  { 양총수: 8,  무리크기: [2, 3], 우리수: 1, 늑대: false },
  8:  { 양총수: 8,  무리크기: [2, 3], 우리수: 2, 늑대: false, 튜토리얼: "분류" },
  9:  { 양총수: 9,  무리크기: [2, 3], 우리수: 2, 늑대: false },
  10: { 양총수: 10, 무리크기: [2, 3], 우리수: 2, 늑대: false, 보스: "여우" },
  15: { 튜토리얼: "호루라기" },
  20: { 보스: "늑대" },
  30: { 보스: "늑대대장" },
};

function 스테이지_규칙(n) {
  const 규칙 = {
    탄: n,
    배경: 배경_순서[Math.floor((n - 1) / 20) % 배경_순서.length], // 20탄 보스는 1장 마지막 (르듀종 확정 2026-09-11)
    양총수: 상한(반올림(5 + n * 0.35), 40),
    무리크기: n >= 50 ? [2, 4] : [2, 3],
    무리간격초: 하한(6 - n * 0.03, 2.5),
    우리수: n < 10 ? 1 : n < 30 ? 2 : n < 60 ? 3 : 4,
    늑대: n >= 15,
    늑대빈도: n >= 15 ? 상한(n * 0.005, 0.25) : 0, // 초당 등장 확률, 상한 25%
    늑대동시최대: n >= 60 ? 3 : 2,
    늑대허용초: 3,                             // 호루라기 없이 버티는 시간
    // 🚨 2026-09-12 형: 「시간이 너무 짧다」. 「양 한 마리에 8초 + 20초」는 과했다.
    //    양이 6초 간격으로 나와서 1탄은 마지막 양이 12초에 나온다. 몰 시간이 30초뿐이었다.
    //    「양 한 마리에 9초 + 40초」 로 늘린다. 1탄 67초.
    제한시간초: 하한(반올림(40 + 상한(반올림(5 + n * 0.35), 40) * 9), 45),
    방해: [],
    보스: null,
    튜토리얼: null,
  };

  // 방해요소는 배경별 고정
  const 배경별_방해 = {
    앞마당: ["바위", "개울"],
    뒷산: ["나무", "낙엽"],
    눈고개: ["얼음", "눈보라"],
    강가: ["다리", "물살"],
    화산: ["용암", "연기"],
  };
  if (n > 6) 규칙.방해 = 배경별_방해[규칙.배경];

  // 🚨 손제작 덮어쓰기를 보스 계산 "앞" 으로 옮겼다.
  //    뒤에 있으면 손제작탄[10].양총수=10 이 보스 강화를 되돌려서
  //    10탄(양10) → 11탄(양9) 로 줄어든다. 올라가야 할 것이 내려갔다.
  if (손제작탄[n]) Object.assign(규칙, 손제작탄[n]);

  // 보스탄: 10탄마다. 시간 무제한, 직전 탄보다 반드시 세다.
  if (n % 10 === 0) {
    규칙.보스 = 규칙.보스 || (n % 20 === 0 ? "늑대" : "여우");
    규칙.제한시간초 = 0;
    // 🚨 2026-09-10 맺음이 고침. 원래는 양총수=20, 늑대빈도=0.03+n*0.001 로 덮어썼다.
    //    그러면 10탄 양10 → 11탄 양9 로 줄고, 20탄 늑대 5.0% 가 19탄 9.5% 보다 순해진다.
    //    보스가 직전 탄보다 쉬우면 보스가 아니다. 그래서 "덮어쓰기"를 "더하기"로 바꾼다.
    규칙.양총수 = 상한(반올림(규칙.양총수 * 1.6), 40);
    규칙.늑대 = true;
    규칙.늑대빈도 = 상한(하한(규칙.늑대빈도, 0.05) * 1.4, 0.35);
  }

  규칙.양색 = 양_색_순서.slice(0, 규칙.우리수);

  // 🚨 제한시간을 여기서 다시 센다.
  //    위에서 한 번 계산했지만 그때는 "공식이 뽑은 양 수" 였다.
  //    손제작탄이 양 수를 바꾸면(1탄: 5→3) 시간이 안 맞는다.
  //    1탄 양 3마리에 60초는 애들 게임이라도 너무 길다. 44초가 된다.
  if (규칙.제한시간초 !== 0) {
    규칙.제한시간초 = 하한(반올림(40 + 규칙.양총수 * 9), 45);
  }

  // 별 조건
  규칙.별조건 = {
    클리어: true,
    손실0: true,
    시간: 규칙.제한시간초 ? 반올림(규칙.제한시간초 * 0.45) : null, // 남은 시간 기준. 0.7 은 44초짜리를 13초에 깨라는 뜻이라 너무 됐다(9/12)
  };

  // 보상
  규칙.보상 = {
    코인: 10 + n * 2,
    뼈다귀_특별: n === 3 ? 10 : 0,   // 3탄 클리어 첫 뽑기 무료
    코인_별당: 5,
    뼈다귀_별3: 1,
    뼈다귀_보스: 규칙.보스 ? 3 : 0,
  };

  return 규칙;
}

// 검증용: node 규칙_생성기.js 로 실행하면 1~100탄 표 출력
if (typeof module !== "undefined" && require.main === module) {
  for (let n = 1; n <= 100; n++) {
    const r = 스테이지_규칙(n);
    console.log(
      `${String(n).padStart(3)} ${r.배경.padEnd(4)} 양${String(r.양총수).padStart(2)} ` +
      `우리${r.우리수} 간격${r.무리간격초.toFixed(1)} 늑대${r.늑대 ? (r.늑대빈도 * 100).toFixed(1) + "%" : "-"} ` +
      `시간${r.제한시간초 || "∞"} ${r.보스 || ""} ${r.튜토리얼 || ""}`
    );
  }
}
